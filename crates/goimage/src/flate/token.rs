/// Port of `flate.token` (token.go:67).
pub(crate) type Token = u32;

/// `literalToken`.
pub(crate) fn literal_token(literal: u32) -> Token {
    LITERAL_TYPE + literal
}

/// `matchToken`.
pub(crate) fn match_token(xlength: u32, xoffset: u32) -> Token {
    MATCH_TYPE + (xlength << LENGTH_SHIFT) + xoffset
}

/// `token.literal`.
pub(crate) fn literal(t: Token) -> u32 {
    t - LITERAL_TYPE
}

/// `token.offset`.
pub(crate) fn offset(t: Token) -> u32 {
    t & OFFSET_MASK
}

/// `token.length`.
pub(crate) fn length(t: Token) -> u32 {
    (t - MATCH_TYPE) >> LENGTH_SHIFT
}

/// `lengthCode`.
pub(crate) fn length_code(len: u32) -> u32 {
    LENGTH_CODES[len as usize]
}

/// `offsetCode` (token.go:88).
pub(crate) fn offset_code(off: u32) -> u32 {
    let n = OFFSET_CODES.len() as u32;
    if off < n {
        return OFFSET_CODES[off as usize];
    }
    if off >> 7 < n {
        return OFFSET_CODES[(off >> 7) as usize] + 14;
    }
    OFFSET_CODES[(off >> 14) as usize] + 28
}
