struct Answer {
    status: u16,
    content_type: String,
    body: Vec<u8>,
    rust: bool,
}

async fn send(
    client: &reqwest::Client,
    method: reqwest::Method,
    base: &str,
    token: &str,
    path: &str,
    body: Option<&[u8]>,
) -> Answer {
    let mut request = client
        .request(method, format!("{base}{path}"))
        .header("Authorization", format!("Bearer {token}"))
        .header("X-Requested-With", "XMLHttpRequest");
    if let Some(body) = body {
        request = request.body(body.to_vec());
    }
    let response = request
        .send()
        .await
        .unwrap_or_else(|e| panic!("{base}{path} is unreachable: {e}"));
    let header = |name: &str| {
        response
            .headers()
            .get(name)
            .and_then(|v| v.to_str().ok())
            .unwrap_or_default()
            .to_owned()
    };
    Answer {
        status: response.status().as_u16(),
        content_type: header("content-type"),
        rust: header("x-mmrs-served-by") == "rust",
        body: response.bytes().await.unwrap().to_vec(),
    }
}

fn assert_same(go: &Answer, rs: &Answer, case: &str) {
    assert!(rs.rust, "{case}: not served by this server");
    assert_eq!(
        go.status,
        rs.status,
        "{case}: Go {} / Rust {}",
        String::from_utf8_lossy(&go.body),
        String::from_utf8_lossy(&rs.body)
    );
    assert_eq!(go.content_type, rs.content_type, "{case}: Content-Type");
    let is_error = serde_json::from_slice::<serde_json::Value>(&go.body)
        .is_ok_and(|v| v.get("status_code").is_some());
    if is_error {
        assert_error_bodies_match_except_known_gaps(&go.body, &rs.body, case);
    } else {
        assert_eq!(
            String::from_utf8_lossy(&go.body),
            String::from_utf8_lossy(&rs.body),
            "{case}"
        );
    }
}

/// One case to the oracle, then to the Rust host, comparing the answers and the Marketplace
/// requests each made. Returns Go's answer.
#[allow(clippy::too_many_arguments)]
async fn both(
    client: &reqwest::Client,
    mock: &Shared,
    rust: &str,
    method: reqwest::Method,
    token: &str,
    path: &str,
    body: Option<&[u8]>,
    case: &str,
) -> Answer {
    take_requests(mock);
    let go = send(client, method.clone(), &oracle(), token, path, body).await;
    let go_requests = take_requests(mock);
    let rs = send(client, method, rust, token, path, body).await;
    let rust_requests = take_requests(mock);
    assert_same(&go, &rs, case);
    assert_eq!(
        go_requests, rust_requests,
        "{case}: the Marketplace requests"
    );
    go
}

/// `install_from_url` to both, each with its own URL — the flaky endpoint counts per key.
async fn both_from_url(
    client: &reqwest::Client,
    rust: &str,
    token: &str,
    go_url: &str,
    rust_url: &str,
    force: &str,
    case: &str,
) -> Answer {
    let path = |url: &str| {
        format!(
            "/api/v4/plugins/install_from_url?force={force}&plugin_download_url={}",
            form_urlencoded::byte_serialize(url.as_bytes()).collect::<String>()
        )
    };
    let go = send(
        client,
        reqwest::Method::POST,
        &oracle(),
        token,
        &path(go_url),
        None,
    )
    .await;
    let rs = send(
        client,
        reqwest::Method::POST,
        rust,
        token,
        &path(rust_url),
        None,
    )
    .await;
    assert_same(&go, &rs, case);
    go
}

/// Put the test key where `SignaturePublicKeyFiles` points both servers.
async fn plant_key(fixture: &serde_json::Value) {
    let pool = common::fixture_pool().await.expect("the stack database");
    let key = String::from_utf8(raw(fixture, "keys", "armored")).expect("armored is text");
    sqlx::query(
        "INSERT INTO configurationfiles (name, data, createat, updateat) VALUES ($1, $2, 1, 1) \
         ON CONFLICT (name) DO UPDATE SET data = EXCLUDED.data",
    )
    .bind(KEY_FILE)
    .bind(key)
    .execute(&pool)
    .await
    .expect("the key file is planted");
}

fn scratch(name: &str) -> (PathBuf, [String; 3]) {
    let root = PathBuf::from(env!("CARGO_TARGET_TMPDIR")).join(name);
    let _ = std::fs::remove_dir_all(&root);
    for dir in ["plugins", "client", "data"] {
        std::fs::create_dir_all(root.join(dir)).unwrap();
    }
    let s = |dir: &str| root.join(dir).to_string_lossy().into_owned();
    let dirs = [s("plugins"), s("client"), format!("{}/", s("data"))];
    (root, dirs)
}

