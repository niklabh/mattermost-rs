//! Cross-server parity for the plugin Marketplace: `GET` and `POST /api/v4/plugins/marketplace`
//! (api4/plugin.go:284, :130) and `POST /api/v4/plugins/install_from_url` (:100), with this
//! server hosting plugins.
//!
//! ```sh
//! scripts/parity.sh --test parity marketplace
//! ```
//!
//! The Marketplace is an outbound service, so this suite **is** the Marketplace: a mock served
//! from the test process on Go's port + 37, which `scripts/go-plugins.sh` points the plugins
//! oracle at (`MarketplaceURL`, with `AllowInsecureDownloadURL` so bundles come over plain http,
//! and `SignaturePublicKeyFiles` naming the test key this suite plants in `ConfigurationFiles`).
//! The Rust host is a second `mm-api` given the same three settings. The bundles, their
//! signatures and the key are `fixtures/behaviour_plugin_signature.json`, generated by
//! `reference/dump`. Each case goes to both servers and the answers are compared, and so are the
//! requests each server made of the Marketplace.
//!
//! The settings a Go oracle cannot be given per case — the remote Marketplace off, the
//! Marketplace off, plugins off, a signature requirement — are covered against further Rust
//! hosts, with Go's answers transcribed from plugin.go; each such assertion says so.

