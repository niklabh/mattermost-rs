#[derive(Default)]
struct Mock {
    /// Every request, as `path?query`, in arrival order.
    requests: Vec<String>,
    /// What `/api/v1/plugins` answers without a `plugin_id`.
    list: (u16, String),
    /// What it answers for a `plugin_id`; `[]` when absent.
    by_id: HashMap<String, (u16, String)>,
    bundles: HashMap<String, Vec<u8>>,
    /// Requests seen per `/flaky/{key}` key: the first two fail.
    flaky: HashMap<String, u32>,
}

type Shared = Arc<Mutex<Mock>>;

async fn plugins(
    axum::extract::State(mock): axum::extract::State<Shared>,
    axum::extract::RawQuery(query): axum::extract::RawQuery,
) -> (axum::http::StatusCode, String) {
    let mut mock = mock.lock().unwrap();
    let query = query.unwrap_or_default();
    mock.requests.push(format!("/api/v1/plugins?{query}"));
    let plugin_id = form_urlencoded::parse(query.as_bytes())
        .find(|(k, _)| k == "plugin_id")
        .map(|(_, v)| v.into_owned())
        .unwrap_or_default();
    let (status, body) = if plugin_id.is_empty() {
        mock.list.clone()
    } else {
        mock.by_id
            .get(&plugin_id)
            .cloned()
            .unwrap_or((200, "[]".to_owned()))
    };
    (axum::http::StatusCode::from_u16(status).unwrap(), body)
}

async fn bundle(
    axum::extract::State(mock): axum::extract::State<Shared>,
    axum::extract::Path(name): axum::extract::Path<String>,
) -> (axum::http::StatusCode, Vec<u8>) {
    let mut mock = mock.lock().unwrap();
    mock.requests.push(format!("/bundles/{name}"));
    match mock.bundles.get(&name) {
        Some(bytes) => (axum::http::StatusCode::OK, bytes.clone()),
        None => (axum::http::StatusCode::NOT_FOUND, Vec::new()),
    }
}

async fn flaky(
    axum::extract::State(mock): axum::extract::State<Shared>,
    axum::extract::Path((key, name)): axum::extract::Path<(String, String)>,
) -> (axum::http::StatusCode, Vec<u8>) {
    let mut mock = mock.lock().unwrap();
    mock.requests.push(format!("/flaky/{key}/{name}"));
    let seen = mock.flaky.entry(key).or_insert(0);
    *seen += 1;
    if *seen <= 2 {
        return (axum::http::StatusCode::SERVICE_UNAVAILABLE, Vec::new());
    }
    match mock.bundles.get(&name) {
        Some(bytes) => (axum::http::StatusCode::OK, bytes.clone()),
        None => (axum::http::StatusCode::NOT_FOUND, Vec::new()),
    }
}

/// Serve the mock on `127.0.0.1:port` (`0` for any), returning its state and base URL.
async fn start_mock(port: u16) -> (Shared, String) {
    let mock: Shared = Arc::default();
    let app = axum::Router::new()
        .route("/api/v1/plugins", axum::routing::get(plugins))
        .route("/bundles/{name}", axum::routing::get(bundle))
        .route("/flaky/{key}/{name}", axum::routing::get(flaky))
        .with_state(Arc::clone(&mock));
    let listener = tokio::net::TcpListener::bind(("127.0.0.1", port))
        .await
        .unwrap_or_else(|e| panic!("the mock Marketplace cannot bind :{port}: {e}"));
    let base = format!("http://127.0.0.1:{}", listener.local_addr().unwrap().port());
    tokio::spawn(async move {
        let _ = axum::serve(listener, app).await;
    });
    (mock, base)
}

fn take_requests(mock: &Shared) -> Vec<String> {
    std::mem::take(&mut mock.lock().unwrap().requests)
}

