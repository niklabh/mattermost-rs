/// The settings a Go oracle cannot be switched between: each is a Rust host of its own, and
/// Go's answer is transcribed from plugin.go and app/plugin.go — except where the main Go server
/// already has the setting, which is compared.
#[tokio::test]
async fn the_gates_follow_go_on_hosts_configured_otherwise() {
    if !stack_enabled() {
        return;
    }
    let client = client();
    let fixture = fixture();
    let admin = go_minted_token(&client).await;
    let (mock, market) = start_mock(0).await;
    mock.lock()
        .unwrap()
        .bundles
        .insert("beta".into(), raw(&fixture, "bundles", "beta"));
    mock.lock().unwrap().list = (200, "[]".to_owned());
    let error_id = |a: &Answer| -> (u16, String) {
        let v: serde_json::Value = serde_json::from_slice(&a.body).unwrap_or_default();
        (a.status, v["id"].as_str().unwrap_or_default().to_owned())
    };
    let beta_url = format!("{market}/bundles/beta");
    let from_url = format!(
        "/api/v4/plugins/install_from_url?plugin_download_url={}",
        form_urlencoded::byte_serialize(beta_url.as_bytes()).collect::<String>()
    );
    let install = format!(r#"{{"id":"{ALPHA}"}}"#);
    use reqwest::Method;

    // The remote Marketplace off: never asked; a local plugin carries no label. The host starts
    // with beta in its file store, which the start-up sync installs.
    let (_root, [plugins, client_dir, data]) = scratch("marketplace-remote-off");
    std::fs::create_dir_all(format!("{data}plugins")).unwrap();
    std::fs::write(
        format!("{data}plugins/mmrs.market.beta.tar.gz"),
        raw(&fixture, "bundles", "beta"),
    )
    .unwrap();
    if let Some(host) = SecondServer::start(
        REMOTE_OFF_PORT,
        &[
            ("MMRS_PLUGIN_HOST", "rust"),
            ("MM_PLUGINSETTINGS_ENABLEREMOTEMARKETPLACE", "false"),
            ("MM_PLUGINSETTINGS_ENABLEUPLOADS", "true"),
            ("MM_PLUGINSETTINGS_MARKETPLACEURL", market.as_str()),
            ("MM_PLUGINSETTINGS_DIRECTORY", plugins.as_str()),
            ("MM_PLUGINSETTINGS_CLIENTDIRECTORY", client_dir.as_str()),
            ("MM_FILESETTINGS_DIRECTORY", data.as_str()),
        ],
    )
    .await
    {
        take_requests(&mock);
        let listed = send(&client, Method::GET, &host.base, &admin, MARKETPLACE, None).await;
        assert_eq!(listed.status, 200);
        let body: serde_json::Value = serde_json::from_slice(&listed.body).unwrap();
        let beta = body
            .as_array()
            .and_then(|a| a.iter().find(|p| p["manifest"]["id"] == "mmrs.market.beta"))
            .expect("the installed plugin is listed");
        assert!(beta.get("labels").is_none(), "no Local label: {beta}");
        assert_eq!(beta["installed_version"], "0.4.0");
        let remote_only = send(
            &client,
            Method::GET,
            &host.base,
            &admin,
            &format!("{MARKETPLACE}?remote_only=true"),
            None,
        )
        .await;
        assert_eq!(
            String::from_utf8_lossy(&remote_only.body),
            "null",
            "nothing remote, nothing local"
        );
        let installed = send(
            &client,
            Method::POST,
            &host.base,
            &admin,
            MARKETPLACE,
            Some(install.as_bytes()),
        )
        .await;
        assert_eq!(
            error_id(&installed),
            (
                500,
                "app.plugin.marketplace_plugins.not_found.app_error".to_owned()
            )
        );
        assert!(
            take_requests(&mock).is_empty(),
            "the Marketplace was not asked"
        );
        // `AllowInsecureDownloadURL` is off here: an http URL is refused before any request.
        let refused = send(&client, Method::POST, &host.base, &admin, &from_url, None).await;
        assert_eq!(
            error_id(&refused),
            (
                400,
                "api.plugin.install.download_failed.app_error".to_owned()
            )
        );
        assert!(
            take_requests(&mock).is_empty(),
            "the insecure URL was not fetched"
        );
    }

    // The Marketplace off: both marketplace routes 501, after plugins-on. A signature requirement
    // refuses `install_from_url` with the plugins-off 501 although uploads are on.
    let (_root, [plugins, client_dir, data]) = scratch("marketplace-off");
    if let Some(host) = SecondServer::start(
        MARKETPLACE_OFF_PORT,
        &[
            ("MMRS_PLUGIN_HOST", "rust"),
            ("MM_PLUGINSETTINGS_ENABLEMARKETPLACE", "false"),
            ("MM_PLUGINSETTINGS_ENABLEUPLOADS", "true"),
            ("MM_PLUGINSETTINGS_REQUIREPLUGINSIGNATURE", "true"),
            ("MM_PLUGINSETTINGS_DIRECTORY", plugins.as_str()),
            ("MM_PLUGINSETTINGS_CLIENTDIRECTORY", client_dir.as_str()),
            ("MM_FILESETTINGS_DIRECTORY", data.as_str()),
        ],
    )
    .await
    {
        for method in [Method::GET, Method::POST] {
            let answer = send(
                &client,
                method,
                &host.base,
                &admin,
                MARKETPLACE,
                Some(install.as_bytes()),
            )
            .await;
            assert_eq!(
                error_id(&answer),
                (501, "app.plugin.marketplace_disabled.app_error".to_owned())
            );
        }
        let refused = send(&client, Method::POST, &host.base, &admin, &from_url, None).await;
        assert_eq!(
            error_id(&refused),
            (501, "app.plugin.disabled.app_error".to_owned())
        );
    }

    // Plugins off: every route here is the 501, ahead of the Marketplace switch.
    let (_root, [plugins, client_dir, data]) = scratch("marketplace-plugins-off");
    if let Some(host) = SecondServer::start(
        PLUGINS_OFF_PORT,
        &[
            ("MMRS_PLUGIN_HOST", "rust"),
            ("MM_PLUGINSETTINGS_ENABLE", "false"),
            ("MM_PLUGINSETTINGS_ENABLEMARKETPLACE", "false"),
            ("MM_PLUGINSETTINGS_ENABLEUPLOADS", "true"),
            ("MM_PLUGINSETTINGS_DIRECTORY", plugins.as_str()),
            ("MM_PLUGINSETTINGS_CLIENTDIRECTORY", client_dir.as_str()),
            ("MM_FILESETTINGS_DIRECTORY", data.as_str()),
        ],
    )
    .await
    {
        for (method, path) in [
            (Method::GET, MARKETPLACE),
            (Method::POST, MARKETPLACE),
            (Method::POST, from_url.as_str()),
        ] {
            let answer = send(
                &client,
                method,
                &host.base,
                &admin,
                path,
                Some(install.as_bytes()),
            )
            .await;
            assert_eq!(
                error_id(&answer),
                (501, "app.plugin.disabled.app_error".to_owned()),
                "{path}"
            );
        }
    }

    // Uploads off, as on the main Go server, which answers `install_from_url` itself: compared.
    let (_root, [plugins, client_dir, data]) = scratch("marketplace-defaults");
    if let Some(host) = SecondServer::start(
        DEFAULTS_PORT,
        &[
            ("MMRS_PLUGIN_HOST", "rust"),
            ("MM_PLUGINSETTINGS_DIRECTORY", plugins.as_str()),
            ("MM_PLUGINSETTINGS_CLIENTDIRECTORY", client_dir.as_str()),
            ("MM_FILESETTINGS_DIRECTORY", data.as_str()),
        ],
    )
    .await
    {
        let go = send(&client, Method::POST, GO, &admin, &from_url, None).await;
        let rs = send(&client, Method::POST, &host.base, &admin, &from_url, None).await;
        assert_same(&go, &rs, "from url: uploads off");
        assert_eq!(
            error_id(&rs),
            (501, "app.plugin.disabled.app_error".to_owned())
        );
    }
}
