fn fixture() -> serde_json::Value {
    serde_json::from_str(include_str!(
        "../../../../fixtures/behaviour_plugin_signature.json"
    ))
    .expect("generated by reference/dump")
}

/// The fixture's base64 for one entry, which is also the Marketplace's `signature` form.
fn b64(fixture: &serde_json::Value, section: &str, name: &str) -> String {
    fixture[section][name]
        .as_str()
        .expect("a base64 string")
        .to_owned()
}

fn raw(fixture: &serde_json::Value, section: &str, name: &str) -> Vec<u8> {
    base64::engine::general_purpose::STANDARD
        .decode(b64(fixture, section, name))
        .expect("base64")
}

