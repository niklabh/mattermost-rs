/// Port of `web.UnsafeContentTypes` (web/files.go:17).
///
/// Matched by **prefix**, so `text/html; charset=utf-8` is unsafe too.
const UNSAFE_CONTENT_TYPES: [&str; 6] = [
    "application/javascript",
    "application/ecmascript",
    "text/javascript",
    "text/ecmascript",
    "application/x-javascript",
    "text/html",
];

