//! Port of `platform/shared/web.WriteFileResponse` (web/files.go:42) and the `http.ServeContent`
//! it ends in.
//!
//! This is the entire wire format of every route that returns file bytes — `GET /files/{id}`,
//! `/thumbnail`, `/preview`, `/public`, and (through [`serve_content`] alone) `downloadExport`.
//! Nine response headers, five conditional-request answers and the whole `Range` family, none of
//! which is Mattermost code: it is Go's standard library, so reading the handler tells you almost
//! none of it.
//!
//! Pinned end to end by `fixtures/behaviour_filestore.json` (`write_file_response`), which was
//! generated by driving the *real* `WriteFileResponse` through `httptest` and recording status,
//! every header, and the body.
//!
//! # Four things the source does not say and the corpus does
//!
//! 1. **`contentSize` does not set `Content-Length`.** `WriteFileResponse` sets it, and then
//!    `ServeContent` overwrites it from the seek size. The parameter's only surviving effect is
//!    in `gzip` mode, where it becomes `X-Uncompressed-Content-Length` instead — which is why
//!    `getFileThumbnail` passing `0` changes nothing about the response.
//! 2. **A 416 loses `Cache-Control`, `Last-Modified` and `Accept-Ranges`.** `serveError`
//!    (fs.go) deletes the first two, and `Accept-Ranges` is set *after* the range handling,
//!    so an unsatisfiable range never reaches the line that sets it.
//! 3. **The Unix epoch is "no modification time"** — `isZeroTime` treats `time.Unix(0,0)` like the
//!    zero `time.Time` — so a `FileInfo` with `update_at: 0` gets no `Last-Modified`. But
//!    `checkIfRange` and `checkIfUnmodifiedSince` test `IsZero()` *only*, so the epoch is a real
//!    date to those two. One value, two meanings, four call sites.
//! 4. **`Content-Disposition` carries the filename twice**, both `url.PathEscape`d — so the
//!    quoted form is percent-escaped as well, and a name with a space is `my%20report.pdf`
//!    inside the quotes.

use axum::body::Body;
