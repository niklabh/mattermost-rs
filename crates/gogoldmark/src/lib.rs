/// The goldmark extensions this port carries (`extension.Strikethrough`, …, `extension.GFM`).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Extension {
    /// `extension.Strikethrough`: `~~text~~` (and `~text~`).
    Strikethrough,
    /// `extension.Table`: GFM pipe tables.
    Table,
    /// `extension.Linkify`: bare `http(s)://`, `ftp://`, `www.` and e-mail autolinks.
    Linkify,
    /// `extension.TaskList`: `[ ]` / `[x]` at the start of a list item.
    TaskList,
    /// `extension.GFM`: Linkify, Table, Strikethrough and TaskList, in that order.
    Gfm,
}

impl Extension {
    fn expand(self) -> &'static [Extension] {
        match self {
            Extension::Gfm => &[
                Extension::Linkify,
                Extension::Table,
                Extension::Strikethrough,
                Extension::TaskList,
            ],
            Extension::Strikethrough => &[Extension::Strikethrough],
            Extension::Table => &[Extension::Table],
            Extension::Linkify => &[Extension::Linkify],
            Extension::TaskList => &[Extension::TaskList],
        }
    }
}

/// `goldmark.DefaultRenderer()`: the HTML renderer at priority 1000.
pub fn default_renderer() -> Renderer {
    Renderer::new().with_node_renderer(Rc::new(html::HtmlRenderer), 1000)
}

/// Port of `goldmark.Markdown` (markdown.go:36): a parser and a renderer.
#[derive(Clone, Debug)]
pub struct Markdown {
    parser: Parser,
    renderer: Renderer,
}

impl Markdown {
    /// `goldmark.New(goldmark.WithExtensions(extensions...))`.
    pub fn new(extensions: &[Extension]) -> Self {
        Markdown::with_renderer(extensions, default_renderer())
    }

    /// `goldmark.New(goldmark.WithExtensions(extensions...), goldmark.WithRenderer(renderer))`.
    /// As in Go, the options apply first and the extensions' `Extend` second, so each
    /// extension's HTML node renderer is added to `renderer` at priority 500.
    pub fn with_renderer(extensions: &[Extension], mut renderer: Renderer) -> Self {
        for &e in extensions {
            for &x in e.expand() {
                match x {
                    Extension::Table => {
                        renderer.add_node_renderer(Rc::new(html::TableHtmlRenderer), 500)
                    }
                    Extension::Strikethrough => {
                        renderer.add_node_renderer(Rc::new(html::StrikethroughHtmlRenderer), 500)
                    }
                    Extension::TaskList => {
                        renderer.add_node_renderer(Rc::new(html::TaskCheckBoxHtmlRenderer), 500)
                    }
                    Extension::Linkify | Extension::Gfm => {}
                }
            }
        }
        Markdown {
            parser: Parser::new(extensions),
            renderer,
        }
    }

    /// Port of `Markdown.Parser`.
    pub fn parser(&self) -> &Parser {
        &self.parser
    }

    /// Port of `Markdown.Renderer`.
    pub fn renderer(&self) -> &Renderer {
        &self.renderer
    }

    /// Port of `Markdown.Convert`: parse `source` and render it into `w`. goldmark's only
    /// failures are the writer's and a node renderer's.
    pub fn convert(&self, source: &[u8], w: &mut dyn Write) -> Result<(), RenderError> {
        let mut ast = self.parser.parse(source);
        let root = ast.root();
        self.renderer.render(w, source, &mut ast, root)
    }
}

/// goldmark with `extensions` and the default HTML renderer, over a string. goldmark's output
/// for UTF-8 input is UTF-8 on every path this port knows of; were it ever not, the invalid
/// bytes would be replaced (`from_utf8_lossy`) — the same thing Go's `encoding/json` does to the
/// string downstream.
pub fn convert(markdown: &str, extensions: &[Extension]) -> String {
    let mut out = Vec::new();
    // Writing into a Vec cannot fail and the default renderers return no errors.
    let _ = Markdown::new(extensions).convert(markdown.as_bytes(), &mut out);
    String::from_utf8_lossy(&out).into_owned()
}
