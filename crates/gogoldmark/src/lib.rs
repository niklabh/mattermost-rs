//! Byte-exact port of [goldmark](https://github.com/yuin/goldmark) **v1.8.2** — the CommonMark
//! parser, its default HTML renderer and the GFM extension — as Mattermost uses it.
//!
//! Mattermost converts markdown with goldmark in two places: the text of every push
//! notification (`utils.StripMarkdown`, goldmark + Strikethrough under a custom node renderer)
//! and the HTML of every notification e-mail (`utils.MarkdownToHTML`, goldmark + GFM). Both are
//! ported on top of this crate in `mm-app`. This crate holds no Mattermost code and must never
//! depend on an `mm-*` crate.
//!
//! What is ported: `text`, the parts of `util` the parser and renderer call, `ast`, the default
//! block and inline parsers with delimiter processing, link reference definitions and the
//! paragraph transformer, `renderer`, `renderer/html` with its **default options**, and the
//! `Strikethrough`, `Table`, `Linkify` and `TaskList` extensions (`GFM` is the four). Not
//! ported: the renderer options (`WithUnsafe`, `WithXHTML`, `WithHardWraps`, East Asian line
//! breaks), the parser options (`WithAttribute`, `WithAutoHeadingID`, escaped spaces), the other
//! extensions (footnotes, definition lists, typographer, CJK) and custom linkify regexps.
//!
//! Parity is asserted against `fixtures/behaviour_goldmark.json`, generated by the Go program
//! `reference/dump/behaviour_goldmark.go` from goldmark itself.

pub mod ast;
pub mod html;
