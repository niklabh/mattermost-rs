//! Port of `server/public/shared/markdown` — Mattermost's hand-written CommonMark subset, "not a
//! full implementation" by its own description, and deliberately **not** replaced by a general
//! CommonMark crate: the server's mention engine (`app/notification.go:1437`,
//! `getExplicitMentions`), the `mmaction://` id scan ([D-044]) and the link-metadata scan
//! (`app/post_metadata.go:777`) walk this parser's tree, so what it does and does not recognise
//! is wire behaviour. Every quirk of the Go package is reproduced and pinned by
//! `fixtures/behaviour_markdown.json` (558 inputs, generated by
//! `reference/dump/behaviour_markdown.go`); see `go_parity` at the bottom of this file.
//!
//! What the server calls: [`inspect`] and [`set_max_post_runes`]. Everything else is here
//! because the parity oracle needs it ([`render_html`] is Go's own test renderer) or because
//! the Go API exports it.
//!
//! **Not** in this subset, and therefore plain text: emphasis, headings, thematic breaks, HTML
//! blocks and inline HTML, `<...>` autolinks, and tables. What *is* recognised: paragraphs with
//! soft and hard breaks, backslash escapes, code spans, fenced and indented code, block quotes,
//! bullet and ordered lists, inline and reference links and images (with a non-standard
//! `=WxH` image dimension suffix), `[label]: dest "title"` definitions, `scheme://` and `www.`
//! autolinks, HTML character references, and `:emoji:`.
//!
