/// The `[]*ReferenceDefinition` half of `Parse`'s result: every definition in the document, in
/// the order the paragraphs holding them were closed. Lookups take the first match.
pub type ReferenceDefinitions<'a> = Vec<ReferenceDefinition<'a>>;

/// Port of `markdown.Parse` (markdown.go:154). An input longer than [`max_len`] bytes parses to
/// an empty document with no definitions; nothing is truncated.
pub fn parse(markdown: &str) -> (Document<'_>, ReferenceDefinitions<'_>) {
    if markdown.len() > max_len() {
        return (Document::default(), Vec::new());
    }
    blocks::parse_unchecked(markdown)
}

