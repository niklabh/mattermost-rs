/// Port of `UserAgent.evalOS` (system.go:12).
///
/// # The platform group, and the two ways of not having one
///
/// Go slices the string between the first `(` and the first `)`. When `)` comes *before* `(`
/// — a malformed agent — both indices are reset to `0` and `len(ua)`, so the "platform group" is
/// the entire string **including its leading byte**, because the slice is `ua[s+1:e]`. When there
/// is no `)` at all, only `e` is reset, so the group starts one byte after the `(`. And when
/// there is no `(` either, `s` is `-1` and `s+1` is `0` — the whole string again. Those three
/// shapes are in the corpus for exactly this reason.
fn eval_os(dest: &mut UserAgent, ua: &str) -> bool {
    let bytes = ua.as_bytes();
    let mut s = index_byte(bytes, b'(');
    let mut e = index_byte(bytes, b')');
    if s > e {
        s = 0;
        e = bytes.len() as isize;
    }
    if e == -1 {
        e = bytes.len() as isize;
    }

    // `ua[s+1:e]`. `s` is -1 when there is no '(' at all, so `s+1` is 0.
    let start = (s + 1).max(0) as usize;
    let end = (e.max(0) as usize).min(bytes.len());
    let agent_platform = if start <= end { &ua[start..end] } else { "" };

    let specs = match agent_platform.find(';') {
        Some(at) => &agent_platform[..at],
        None => agent_platform,
    };

    if specs == "android" {
        eval_linux(dest, ua, agent_platform);
    } else if specs == "bb10" || specs == "playbook" {
        dest.platform = Platform::Blackberry;
        dest.os_name = OsName::Blackberry;
    } else if specs == "x11" || specs == "linux" {
        eval_linux(dest, ua, agent_platform);
    } else if specs.starts_with("ipad")
        || specs.starts_with("iphone")
        || specs.starts_with("ipod touch")
        || specs.starts_with("ipod")
    {
        eval_ios(dest, specs, agent_platform);
    } else if specs == "macintosh" {
        eval_macintosh(dest, ua);
    } else if ua.contains("blackberry") || ua.contains("playbook") {
        dest.platform = Platform::Blackberry;
        dest.os_name = OsName::Blackberry;
    } else if agent_platform.contains("windows phone ") {
        eval_windows_phone(dest, agent_platform);
    } else if ua.contains("windows ") || ua.contains("microsoft-cryptoapi") {
        eval_windows(dest, ua);
    } else if ua.contains("kindle/") || amazon_fire_fingerprint(agent_platform) {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::Kindle;
    } else if ua.contains("linux") {
        eval_linux(dest, ua, agent_platform);
    } else if ua.contains("webos") || ua.contains("hpwos") {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::WebOS;
    } else if ua.contains("nintendo") {
        dest.platform = Platform::Nintendo;
        dest.os_name = OsName::Nintendo;
    } else if ua.contains("playstation") || ua.contains("vita") || ua.contains("psp") {
        dest.platform = Platform::Playstation;
        dest.os_name = OsName::Playstation;
    } else if ua.contains("android") {
        eval_linux(dest, ua, agent_platform);
    } else if ua.contains("cfnetwork") && ua.contains("darwin") {
        eval_macintosh(dest, ua);
    } else {
        dest.platform = Platform::Unknown;
        dest.os_name = OsName::Unknown;
    }

    dest.maybe_bot()
}

/// `strings.IndexRune` on an ASCII byte: the index, or -1.
fn index_byte(haystack: &[u8], needle: u8) -> isize {
    match haystack.iter().position(|b| *b == needle) {
        Some(at) => at as isize,
        None => -1,
    }
}

/// Port of `amazonFireFingerprint`, `regexp.MustCompile("\\s(k[a-z]{3,5}|sd\\d{4}ur)\\s")`
/// (system.go:10), matched anywhere in the string.
///
/// Written out rather than pulled in as a regex crate: it is one alternation over ASCII, and a
/// dependency added for four lines of matching is a dependency the next reader has to audit.
/// `\s` in Go's regexp is `[\t\n\f\r ]` — **not** `\v`, and not any Unicode space.
fn amazon_fire_fingerprint(text: &str) -> bool {
    let bytes = text.as_bytes();
    for start in 0..bytes.len() {
        if !is_go_space(bytes[start]) {
            continue;
        }
        // `k[a-z]{3,5}` — greedy, but a regex search succeeds on any length that lets the
        // trailing `\s` match, so every length in range is tried.
        if bytes.get(start + 1) == Some(&b'k') {
            for run in 3..=5usize {
                let close = start + 2 + run;
                if close < bytes.len()
                    && bytes[start + 2..close].iter().all(u8::is_ascii_lowercase)
                    && is_go_space(bytes[close])
                {
                    return true;
                }
            }
        }
        // `sd\d{4}ur`
        let close = start + 1 + 8;
        if close < bytes.len()
            && &bytes[start + 1..start + 3] == b"sd"
            && bytes[start + 3..start + 7].iter().all(u8::is_ascii_digit)
            && &bytes[start + 7..start + 9] == b"ur"
            && is_go_space(bytes[close])
        {
            return true;
        }
    }
    false
}

/// Go's `regexp` `\s`: `[\t\n\f\r ]`.
fn is_go_space(byte: u8) -> bool {
    matches!(byte, b'\t' | b'\n' | 0x0c | b'\r' | b' ')
}

/// Port of `UserAgent.evalLinux` (system.go:117).
fn eval_linux(dest: &mut UserAgent, ua: &str, agent_platform: &str) {
    if ua.contains("kindle") || amazon_fire_fingerprint(agent_platform) {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::Kindle;
        find_version_number(&mut dest.os_version, agent_platform, "android ");
    } else if ua.contains("android") || ua.contains("googletv") {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::Android;
        find_version_number(&mut dest.os_version, agent_platform, "android ");
    } else if ua.contains("cros") {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::ChromeOS;
    } else if ua.contains("webos") || ua.contains("hpwos") {
        dest.platform = Platform::Linux;
        dest.os_name = OsName::WebOS;
    } else {
        // Go's last two arms — the `x11|bsd|suse|debian|ubuntu` case and the `default` — assign
        // exactly the same pair, so they are folded. Kept as one arm deliberately: splitting it
        // would invite a reader to make them differ.
        dest.platform = Platform::Linux;
        dest.os_name = OsName::Linux;
    }
}

/// Port of `UserAgent.evaliOS` (system.go:157).
fn eval_ios(dest: &mut UserAgent, ua_platform: &str, agent_platform: &str) {
    if ua_platform.starts_with("iphone") {
        dest.platform = Platform::IPhone;
        dest.os_name = OsName::IOS;
        get_ios_version(&mut dest.os_version, agent_platform);
    } else if ua_platform.starts_with("ipad") {
        dest.platform = Platform::IPad;
        dest.os_name = OsName::IOS;
        get_ios_version(&mut dest.os_version, agent_platform);
    } else if ua_platform.starts_with("ipod touch") || ua_platform.starts_with("ipod") {
        dest.platform = Platform::IPod;
        dest.os_name = OsName::IOS;
        get_ios_version(&mut dest.os_version, agent_platform);
    } else {
        // Unreachable from `evalOS`, whose guard is the same four prefixes. Reproduced because
        // it is not obviously unreachable and the default is *iPad*, not unknown.
        dest.platform = Platform::IPad;
        dest.os_name = OsName::Unknown;
    }
}

/// Port of `UserAgent.evalWindowsPhone` (system.go:182).
///
/// The platform is set unconditionally and the *name* only when a version parses — so a Windows
/// Phone UA with an unparseable version is platform `WindowsPhone`, os `Unknown`, which
/// Mattermost renders as `"Windows Phone"` / `""`.
fn eval_windows_phone(dest: &mut UserAgent, agent_platform: &str) {
    dest.platform = Platform::WindowsPhone;
    if find_version_number(&mut dest.os_version, agent_platform, "windows phone os ")
        || find_version_number(&mut dest.os_version, agent_platform, "windows phone ")
    {
        dest.os_name = OsName::WindowsPhone;
    } else {
        dest.os_name = OsName::Unknown;
    }
}

/// Port of `UserAgent.evalWindows` (system.go:192).
fn eval_windows(dest: &mut UserAgent, ua: &str) {
    if ua.contains("xbox") {
        dest.platform = Platform::Xbox;
        dest.os_name = OsName::Xbox;
        if !find_version_number(&mut dest.os_version, ua, "windows nt ") {
            dest.os_version = Version {
                major: 6,
                minor: 0,
                patch: 0,
            };
        }
    } else if !ua.contains("windows ") {
        // Reached via the `microsoft-cryptoapi` arm of `evalOS`.
        dest.platform = Platform::Windows;
        dest.os_name = OsName::Unknown;
    } else if ua.contains("windows nt ")
        && find_version_number(&mut dest.os_version, ua, "windows nt ")
    {
        dest.platform = Platform::Windows;
        dest.os_name = OsName::Windows;
    } else if ua.contains("windows xp") {
        dest.platform = Platform::Windows;
        dest.os_name = OsName::Windows;
        dest.os_version = Version {
            major: 5,
            minor: 1,
            patch: 0,
        };
    } else {
        dest.platform = Platform::Windows;
        dest.os_name = OsName::Unknown;
    }
}

/// Port of `UserAgent.evalMacintosh` (system.go:222).
fn eval_macintosh(dest: &mut UserAgent, ua_platform_group: &str) {
    dest.platform = Platform::Mac;
    if let Some(at) = ua_platform_group.find("os x ") {
        dest.os_name = OsName::MacOSX;
        parse_version(&mut dest.os_version, &ua_platform_group[at + 5..]);
        return;
    }
    dest.os_name = OsName::Unknown;
}

/// Port of `Version.findVersionNumber` (system.go:232).
fn find_version_number(version: &mut Version, text: &str, marker: &str) -> bool {
    match text.find(marker) {
        Some(at) => parse_version(version, &text[at + marker.len()..]),
        None => false,
    }
}

/// Port of `OS.getiOSVersion` (system.go:241).
///
/// Note the fall-through: when neither marker is present it parses the platform group **from the
/// start**, which for `iphone; cpu …` begins with a letter and therefore parses nothing. That is
/// why `Mattermost Mobile/2.19.0 (iPhone; iOS 17.5.1)` records an OS version of `0.0.0` even
/// though the string plainly says 17.5.1.
fn get_ios_version(version: &mut Version, ua_platform_group: &str) {
    if let Some(at) = ua_platform_group.find("cpu iphone os ") {
        parse_version(version, &ua_platform_group[at + 14..]);
        return;
    }
    if let Some(at) = ua_platform_group.find("cpu os ") {
        parse_version(version, &ua_platform_group[at + 7..]);
        return;
    }
    parse_version(version, ua_platform_group);
}

/// Port of `Version.parse` (system.go:272), which is **not** a version parser and must not be
/// replaced by one.
///
/// It refuses outright unless the first byte is a digit, and then loops three times pulling one
/// number out of the front of the remaining string. Inside each pass:
///
/// - a non-digit ends the number and the remainder restarts **after** it, so `10_15_7` yields
///   10, 15, 7 exactly as `10.15.7` does;
/// - the first digit seeds the value; a subsequent digit while the value is still `0` is either
///   another `0` (skipped, and the pass continues) or a non-zero, at which point the remainder
///   restarts **at** that digit and the pass ends with the value still `0`. So `"0a"` is a major
///   of 0, `"01"` is a major of 0 *and* a minor of 1, and `"007"` is 0 then 7 — a leading zero is
///   not stripped, it consumes a whole pass;
/// - reaching the end of the string empties it, so the remaining passes see `""` and contribute
///   zero.
///
/// Every one of those is observable in `Chrome/127.0.0.0`, which becomes `127.0` and not `127`.
fn parse_version(version: &mut Version, text: &str) -> bool {
    let bytes = text.as_bytes();
    if bytes.is_empty() || !bytes[0].is_ascii_digit() {
        return false;
    }

    let mut rest: &[u8] = bytes;
    for pass in 0..3 {
        let mut empty = true;
        let mut val: i64 = 0;
        let last = rest.len().wrapping_sub(1);

        for k in 0..rest.len() {
            let c = rest[k];
            if c.is_ascii_digit() {
                if empty {
                    val = i64::from(c - b'0');
                    empty = false;
                    if k == last {
                        rest = &rest[..0];
                    }
                    continue;
                }
                if val == 0 {
                    if c == b'0' {
                        if k == last {
                            rest = &rest[..0];
                        }
                        continue;
                    }
                    rest = &rest[k..];
                    break;
                }
                val = 10 * val + i64::from(c - b'0');
                if k == last {
                    rest = &rest[..0];
                }
                continue;
            }
            rest = &rest[k + 1..];
            break;
        }

        match pass {
            0 => version.major = val,
            1 => version.minor = val,
            _ => version.patch = val,
        }
    }
    true
}

