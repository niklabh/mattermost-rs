//! Port of `channels/app/user_agent.go` and the half of `github.com/avct/uasurfer` it stands on.
//!
//! # Why a user-agent parser is in scope at all
//!
//! `DoLogin` writes three props into every session it creates (app/login.go:186-193):
//!
//! ```text
//! session.AddProp(model.SessionPropPlatform, plat)
//! session.AddProp(model.SessionPropOs, os)
//! session.AddProp(model.SessionPropBrowser, fmt.Sprintf("%v/%v", bname, bversion))
//! ```
//!
//! Those land in `Sessions.Props` and are echoed verbatim by `GET /users/{user_id}/sessions`,
//! which this server already answers. They are wire format, not telemetry, so `login` cannot be
//! served without reproducing them.
//!
//! # What is ported and what is not
//!
//! uasurfer computes three things: `OS`, `Browser` and `DeviceType`. Mattermost reads the first
//! two and never the third, so `evalDevice` and everything below it is **not** ported — and
//! neither are the bot names beyond what `IsBot` needs, since a bot classification changes the OS
//! and platform to `Bot` and that *is* observable. The parse order is uasurfer's own and is load
//! bearing: `parse` short-circuits on the empty string, then runs `evalOS`, then
//! `evalBrowserName`, and only reaches `evalBrowserVersion` when neither of those reported a bot.
//!
//! # The oracle
//!
//! `fixtures/behaviour_user_agent.json` is generated by `reference/dump/behaviour_user_agent.go`,
//! which calls the **real** `uasurfer.Parse` over a corpus and records both its raw output and
//! the three props Mattermost derives. The `go_parity` module below asserts this port against
//! every row, field by field, so the parser is checked against Go's answer rather than against a
//! reading of Go's source.
//!
//! Two of Go's habits survive here because they are visible on the wire:
//!
//! - **`Version.parse` is not a version parser.** It walks the string three times pulling out
//!   runs of digits with an idiosyncratic leading-zero rule, and it is the reason
//!   `Chrome/127.0.0.0` reports a version of `127.0` while `Chrome/49.0.2623.112` reports
//!   `49.0.2623` — the formatter drops the patch only when it is zero.
//! - **`getBrowserName` renames `BrowserIE` to "Edge" when the major version exceeds 11**, so the
//!   browser *version* decides the browser *name*, and the version is computed after the name.

