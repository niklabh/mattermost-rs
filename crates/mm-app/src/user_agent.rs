/// Port of `UserAgent.evalBrowserName` (browser.go:22).
///
/// # The `goto notwebkit`
///
/// Go's webkit switch ends in `default: goto notwebkit`, which jumps **out** of the switch to the
/// label below it — so an agent that says `applewebkit` but matches none of the webkit arms is
/// evaluated a second time against the non-webkit list. Modelled here by letting the webkit
/// branch return `None` and falling through, which is the same control flow without the label.
fn eval_browser_name(dest: &mut UserAgent, ua: &str) -> bool {
    // Blackberry goes first because it reads as MSIE and Safari.
    if ua.contains("blackberry")
        || ua.contains("playbook")
        || ua.contains("bb10")
        || ua.contains("rim ")
    {
        dest.browser_name = BrowserName::Blackberry;
        return dest.maybe_bot();
    }

    if ua.contains("applewebkit")
        && let Some(name) = webkit_browser_name(ua)
    {
        dest.browser_name = name;
        return dest.maybe_bot();
    }

    dest.browser_name = if ua.contains("qq/") || ua.contains("qqbrowser/") {
        BrowserName::QQ
    } else if ua.contains("msie") || ua.contains("trident") {
        BrowserName::IE
    } else if ua.contains("gecko")
        && (ua.contains("firefox")
            || ua.contains("iceweasel")
            || ua.contains("seamonkey")
            || ua.contains("icecat"))
    {
        BrowserName::Firefox
    } else if ua.contains("presto") || ua.contains("opera") {
        BrowserName::Opera
    } else if ua.contains("ucbrowser") {
        BrowserName::UCBrowser
    } else if ua.contains("applebot") {
        BrowserName::AppleBot
    } else if ua.contains("baiduspider") {
        BrowserName::BaiduBot
    } else if ua.contains("adidxbot") || ua.contains("bingbot") || ua.contains("bingpreview") {
        BrowserName::BingBot
    } else if ua.contains("duckduckbot") {
        BrowserName::DuckDuckGoBot
    } else if ua.contains("facebot") || ua.contains("facebookexternalhit") {
        BrowserName::FacebookBot
    } else if ua.contains("googlebot") {
        BrowserName::GoogleBot
    } else if ua.contains("linkedinbot") {
        BrowserName::LinkedInBot
    } else if ua.contains("msnbot") {
        BrowserName::MsnBot
    } else if ua.contains("pingdom.com_bot") {
        BrowserName::PingdomBot
    } else if ua.contains("twitterbot") {
        BrowserName::TwitterBot
    } else if ua.contains("yandex") || ua.contains("yadirectfetcher") {
        BrowserName::YandexBot
    } else if ua.contains("yahoo") {
        BrowserName::YahooBot
    } else if ua.contains("coccocbot") {
        BrowserName::CocCocBot
    } else if ua.contains("phantomjs") {
        BrowserName::Bot
    } else {
        BrowserName::Unknown
    };

    dest.maybe_bot()
}

/// The `applewebkit` switch of `evalBrowserName`. `None` is Go's `goto notwebkit`.
///
