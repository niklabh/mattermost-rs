/// `maxUserAgentVersionLength` (user_agent.go:13). MM-55320: caps the version string a client can
/// make the server store.
const MAX_USER_AGENT_VERSION_LENGTH: usize = 128;

/// The three props `DoLogin` writes, as it writes them.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SessionUserAgentProps {
    /// `model.SessionPropPlatform`.
    pub platform: String,
    /// `model.SessionPropOs`. Genuinely `""` for anything uasurfer does not recognise, which
    /// includes every `curl` and every plain HTTP client.
    pub os: String,
    /// `model.SessionPropBrowser`, already joined as `fmt.Sprintf("%v/%v", name, version)`. It is
    /// one prop in Go, not two, so it is one field here.
    pub browser: String,
}

/// Everything `DoLogin` derives from one `User-Agent` header (app/login.go:183-193).
#[must_use]
pub fn session_props(raw_user_agent: &str) -> SessionUserAgentProps {
    let ua = parse(raw_user_agent);
    SessionUserAgentProps {
        platform: platform_name(&ua, raw_user_agent).to_owned(),
        os: os_name(&ua, raw_user_agent).to_owned(),
        browser: format!(
            "{}/{}",
            browser_name(&ua, raw_user_agent),
            browser_version(&ua, raw_user_agent)
        ),
    }
}

/// Port of `getPlatformName` (user_agent.go:27).
///
/// The `Mattermost Mobile/` fallback fires only when uasurfer found **nothing**, and its last arm
/// is `Linux` — so a mobile agent with no recognisable platform is reported as Linux/Android, not
/// as unknown. Note the substring test is against the **raw** header, not the lowercased one, so
/// the capitalisation of `Mattermost Mobile/`, `iPhone` and `iPad` is significant.
fn platform_name(ua: &UserAgent, raw: &str) -> &'static str {
    let mut platform = ua.platform;

    if platform == Platform::Unknown && raw.contains("Mattermost Mobile/") {
        platform = if raw.contains("iPhone") {
            Platform::IPhone
        } else if raw.contains("iPad") {
            Platform::IPad
        } else {
            Platform::Linux
        };
    }

    match platform {
        Platform::Unknown => "Unknown",
        Platform::Windows => "Windows",
        Platform::Mac => "Macintosh",
        Platform::Linux => "Linux",
        Platform::IPad => "iPad",
        Platform::IPhone => "iPhone",
        Platform::IPod => "iPod",
        Platform::Blackberry => "BlackBerry",
        Platform::WindowsPhone => "Windows Phone",
        // `platformNames` has no entry for Playstation, Xbox, Nintendo or Bot, so Go's
        // `name, ok := platformNames[platform]; if !ok` returns the Unknown entry for all four.
        Platform::Playstation | Platform::Xbox | Platform::Nintendo | Platform::Bot => "Unknown",
    }
}

/// Port of `getOSName` (user_agent.go:61).
///
/// # Windows is a table of marketing names and the table has holes
///
/// NT 5.0/5.1/5.2/6.0/6.1/6.2/6.3 and major 10 have names; **NT 6.4 and NT 11 do not** and fall
/// to a bare `"Windows"`. The `major == 10` arm ignores the minor entirely, so NT 10.1 is also
/// "Windows 10". A port that mapped NT versions arithmetically would get all three wrong.
fn os_name(ua: &UserAgent, raw: &str) -> &'static str {
    if ua.os_name == OsName::Windows {
        let (major, minor) = (ua.os_version.major, ua.os_version.minor);
        return match (major, minor) {
            (5, 0) => "Windows 2000",
            (5, 1) => "Windows XP",
            (5, 2) => "Windows XP x64 Edition",
            (6, 0) => "Windows Vista",
            (6, 1) => "Windows 7",
            (6, 2) => "Windows 8",
            (6, 3) => "Windows 8.1",
            (10, _) => "Windows 10",
            _ => "Windows",
        };
    }

    let mut name = ua.os_name;
    if name == OsName::Unknown && raw.contains("Mattermost Mobile/") {
        // Both iPhone and iPad map to iOS here; only the *platform* tells them apart.
        name = if raw.contains("iPhone") || raw.contains("iPad") {
            OsName::IOS
        } else {
            OsName::Android
        };
    }

    match name {
        OsName::Unknown => "",
        OsName::WindowsPhone => "Windows Phone",
        // Unreachable: the `Windows` arm returned above. Kept so the match is exhaustive over the
        // enum rather than over a reading of the control flow.
        OsName::Windows => "Windows",
        OsName::MacOSX => "Mac OS",
        OsName::IOS => "iOS",
        OsName::Android => "Android",
        OsName::Blackberry => "BlackBerry",
        OsName::ChromeOS => "Chrome OS",
        OsName::Kindle => "Kindle",
        OsName::WebOS => "webOS",
        OsName::Linux => "Linux",
        // `osNames` has no entry for these four, so Go returns the `OSUnknown` entry — `""`.
        OsName::Playstation | OsName::Xbox | OsName::Nintendo | OsName::Bot => "",
    }
}

/// Port of `getBrowserName` (user_agent.go:169).
///
/// # Three substring checks run before uasurfer's answer is consulted at all
///
/// `Electron` **or** `Mattermost`-but-not-`Mattermost Mobile` is "Desktop App";
/// `Mattermost Mobile` is "Mobile App"; `mmctl` is "mmctl". All three are on the **raw** header.
/// The first is why the Mattermost desktop client — which is Chrome — never reports as Chrome.
fn browser_name(ua: &UserAgent, raw: &str) -> &'static str {
    if raw.contains("Electron")
        || (raw.contains("Mattermost") && !raw.contains("Mattermost Mobile"))
    {
        return "Desktop App";
    }
    if raw.contains("Mattermost Mobile") {
        return "Mobile App";
    }
    if raw.contains("mmctl") {
        return "mmctl";
    }

    if ua.browser_name == BrowserName::IE && ua.browser_version.major > 11 {
        return "Edge";
    }

    match ua.browser_name {
        BrowserName::Chrome => "Chrome",
        BrowserName::IE => "Internet Explorer",
        BrowserName::Safari => "Safari",
        BrowserName::Firefox => "Firefox",
        BrowserName::Android => "Android",
        BrowserName::Opera => "Opera",
        BrowserName::Blackberry => "BlackBerry",
        // Everything else — including every bot and every browser uasurfer names but Mattermost
        // does not — has no entry in `browserNames`, so Go falls back to the Unknown entry.
        _ => "Unknown",
    }
}

/// Port of `getBrowserVersion` (user_agent.go:134) over `versionPrefixes` (user_agent.go:127).
///
/// The four prefixes are tried **in order** against the raw header and the first hit wins, taking
/// the whitespace-delimited field that follows it. So a desktop agent reading
/// `Mattermost/5.10.0 Chrome/126…` reports `5.10.0` and never reaches uasurfer. A prefix with
/// nothing after it (`"Mattermost/"`) has no fields and falls through to the next prefix, and
/// then to uasurfer.
fn browser_version(ua: &UserAgent, raw: &str) -> String {
    for prefix in ["Mattermost Mobile/", "Mattermost/", "mmctl/", "Franz/"] {
        if let Some((_, after)) = raw.split_once(prefix)
            && let Some(field) = after.split_ascii_whitespace().next()
        {
            return limit_string_length(field, MAX_USER_AGENT_VERSION_LENGTH).to_owned();
        }
    }
    ua_version(ua.browser_version)
}

/// Port of `limitStringLength` (user_agent.go:146). Counted in **bytes**, and the truncation is a
/// raw slice — so a multi-byte character straddling the limit would be cut in half. Rust cannot
/// slice a `str` there, so the cut falls back to the last character boundary at or below the
/// limit; the only way to reach it is a version field of more than 128 bytes containing non-ASCII,
/// which no client sends and which Go would answer with invalid UTF-8 anyway.
fn limit_string_length(field: &str, limit: usize) -> &str {
    if field.len() <= limit {
        return field;
    }
    let mut end = limit;
    while end > 0 && !field.is_char_boundary(end) {
        end -= 1;
    }
    &field[..end]
}

/// Port of `getUAVersion` (user_agent.go:151). **Two components when the patch is zero**, three
/// otherwise — so `127.0.0.0` renders as `127.0` and `49.0.2623.112` as `49.0.2623`.
fn ua_version(version: Version) -> String {
    let mut out = String::new();
    if version.patch == 0 {
        let _ = write!(out, "{}.{}", version.major, version.minor);
    } else {
        let _ = write!(out, "{}.{}.{}", version.major, version.minor, version.patch);
    }
    out
}

/// Port of `utils.IsMobileRequest` (channels/utils/utils.go:232).
///
/// Five case-sensitive substrings on the raw header and nothing else — no parsing, and no
/// agreement with [`parse`]. `DoLogin` uses it to choose between `SessionLengthMobileInHours` and
/// `SessionLengthWebInHours`, so a desktop browser whose UA happens to say "Mobile" gets the
/// mobile session length. That is Go's rule; it is also why an explicit `device_id` overrides it
/// (app/login.go:155).
#[must_use]
pub fn is_mobile_request(raw_user_agent: &str) -> bool {
    if raw_user_agent.is_empty() {
        return false;
    }
    ["Mobile", "Android", "iOS", "iPhone", "iPad"]
        .iter()
        .any(|keyword| raw_user_agent.contains(keyword))
}

