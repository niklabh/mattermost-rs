/// Port of `UserAgent.evalBrowserVersion` (browser.go:163).
///
/// The generic `version/#` probe runs first for every browser **except** Chrome — Go's comment
/// says Android vendors hijack that field — and returns immediately if it finds a number. Safari
/// has no version token of its own at all: it copies the *OS* version and adds one below major 4,
/// which is a rule from the iOS 3 era that still fires on the corpus.
fn eval_browser_version(dest: &mut UserAgent, ua: &str) {
    if dest.browser_name != BrowserName::Chrome
        && find_version_number(&mut dest.browser_version, ua, "version/")
    {
        return;
    }

    match dest.browser_name {
        BrowserName::Chrome => {
            let _ = find_version_number(&mut dest.browser_version, ua, "chrome/")
                || find_version_number(&mut dest.browser_version, ua, "crios/")
                || find_version_number(&mut dest.browser_version, ua, "crmo/");
        }
        BrowserName::Yandex => {
            find_version_number(&mut dest.browser_version, ua, "yabrowser/");
        }
        BrowserName::QQ => {
            if find_version_number(&mut dest.browser_version, ua, "qq/") {
                return;
            }
            find_version_number(&mut dest.browser_version, ua, "qqbrowser/");
        }
        BrowserName::IE => {
            if find_version_number(&mut dest.browser_version, ua, "msie ")
                || find_version_number(&mut dest.browser_version, ua, "edge/")
                || find_version_number(&mut dest.browser_version, ua, "edgios/")
                || find_version_number(&mut dest.browser_version, ua, "edga/")
                || find_version_number(&mut dest.browser_version, ua, "edg/")
            {
                return;
            }

            // Trident 3-7 map to MSIE 7-11 by adding four.
            if find_version_number(&mut dest.browser_version, ua, "trident/")
                && dest.browser_version.major >= 3
                && dest.browser_version.major <= 7
            {
                dest.browser_version.major += 4;
            }
        }
        BrowserName::Firefox => {
            let _ = find_version_number(&mut dest.browser_version, ua, "firefox/")
                || find_version_number(&mut dest.browser_version, ua, "fxios/");
        }
        BrowserName::Safari => {
            dest.browser_version = dest.os_version;
            if dest.browser_version.major <= 3 && dest.browser_version.major >= 1 {
                dest.browser_version.major += 1;
            }
        }
        BrowserName::UCBrowser => {
            find_version_number(&mut dest.browser_version, ua, "ucbrowser/");
        }
        BrowserName::Opera => {
            let _ = find_version_number(&mut dest.browser_version, ua, "opr/")
                || find_version_number(&mut dest.browser_version, ua, "opios/")
                || find_version_number(&mut dest.browser_version, ua, "opera/");
        }
        BrowserName::Silk => {
            find_version_number(&mut dest.browser_version, ua, "silk/");
        }
        BrowserName::Spotify => {
            find_version_number(&mut dest.browser_version, ua, "spotify/");
        }
        BrowserName::CocCoc => {
            find_version_number(&mut dest.browser_version, ua, "coc_coc_browser/");
        }
        _ => {}
    }
}

