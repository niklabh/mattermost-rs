/// uasurfer's `Version` (uasurfer.go:131). Three `int`s, defaulting to zero.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct Version {
    pub major: i64,
    pub minor: i64,
    pub patch: i64,
}

/// uasurfer's `UserAgent`, minus `DeviceType`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UserAgent {
    pub platform: Platform,
    pub os_name: OsName,
    pub os_version: Version,
    pub browser_name: BrowserName,
    pub browser_version: Version,
}

impl Default for UserAgent {
    fn default() -> Self {
        UserAgent {
            platform: Platform::Unknown,
            os_name: OsName::Unknown,
            os_version: Version::default(),
            browser_name: BrowserName::Unknown,
            browser_version: Version::default(),
        }
    }
}

impl UserAgent {
    /// `UserAgent.IsBot` (uasurfer.go:175), minus the `DeviceType` it also sets.
    fn is_bot(&self) -> bool {
        self.browser_name.is_bot() || self.os_name == OsName::Bot || self.platform == Platform::Bot
    }

    /// `UserAgent.maybeBot` (system.go:105). Returns whether the agent was a bot, and rewrites
    /// the OS fields when it was — which is why a bot's `platform` prop is `Unknown` rather than
    /// whatever its UA claimed: `PlatformBot` has no entry in Mattermost's `platformNames`.
    fn maybe_bot(&mut self) -> bool {
        if self.is_bot() {
            self.platform = Platform::Bot;
            self.os_name = OsName::Bot;
            return true;
        }
        false
    }
}

/// Port of `uasurfer.Parse` (uasurfer.go:190) together with `parse` (uasurfer.go:205).
///
/// The three-way switch is the whole control flow and the order is load bearing:
///
/// 1. an **empty** normalised string is all-unknown and nothing else runs;
/// 2. `evalOS` runs and, if it reported a bot, nothing else runs;
/// 3. `evalBrowserName` runs and, if it reported a bot, nothing else runs;
/// 4. only then is the browser *version* evaluated.
///
/// So a bot's browser version is always `0.0`, and so is that of anything whose OS evaluation
/// tripped the bot check. `evalDevice` is the fourth step in Go and is not ported — Mattermost
/// never reads `DeviceType`.
#[must_use]
pub fn parse(raw: &str) -> UserAgent {
    let ua = normalise(raw);
    let mut dest = UserAgent::default();

    if ua.is_empty() {
        return dest;
    }
    if eval_os(&mut dest, &ua) {
        return dest;
    }
    if eval_browser_name(&mut dest, &ua) {
        return dest;
    }
    eval_browser_version(&mut dest, &ua);
    dest
}

/// Port of `normalise` (uasurfer.go:215).
///
/// Go lowers ASCII byte-wise into a 1024-byte stack buffer and falls back to `strings.ToLower`
/// the moment it meets a byte above 127 — or when the string is longer than 1024. Both paths
/// produce the same answer for ASCII; for anything else the fallback does full Unicode
/// lowercasing. `str::to_lowercase` is Rust's equivalent of the fallback, and `is_ascii` picks
/// the same branch Go's `copyLower` does, so the two agree without reproducing the buffer.
fn normalise(raw: &str) -> String {
    if raw.is_ascii() {
        raw.to_ascii_lowercase()
    } else {
        raw.to_lowercase()
    }
}

