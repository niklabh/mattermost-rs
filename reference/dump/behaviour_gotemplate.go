var gotemplatePropRe = regexp.MustCompile(`\.Props\.([A-Za-z0-9_]+)`)
var gotemplateHTMLRe = regexp.MustCompile(`\.HTML\.([A-Za-z0-9_]+)`)

func gotemplateIsURLKey(k string) bool {
	for _, s := range []string{"URL", "Url", "Link", "Src", "Photo", "Icon", "Subpath", "Path"} {
		if strings.Contains(k, s) {
			return true
		}
	}
	return false
}

func sp(s string) *string { return &s }

// gotemplateMattermostData builds one variant of the data graph. Every key any template reads is
// populated, each with a value that names its key so a misplaced substitution cannot pass.
func gotemplateMattermostData(variant string, props, htmls []string) templates.Data {
	if variant == "missing" {
		return templates.Data{}
	}
	d := templates.Data{Props: map[string]any{}, HTML: map[string]htmltemplate.HTML{}}
	for i, k := range props {
		switch variant {
		case "escape":
			if gotemplateIsURLKey(k) {
				d.Props[k] = "https://ex.com/" + k + "/a b/é?q=<1>&r='2'&p=100%#f\"g"
			} else {
				d.Props[k] = k + ` <b>&amp;</b> "dq" 'sq' é 日本 +1`
			}
		case "javascript":
			if gotemplateIsURLKey(k) {
				d.Props[k] = "javascript:alert(\"" + k + "\")"
			} else {
				d.Props[k] = k + " ünï\u2028\u00a0\x00 </script> `${x}`"
			}
		case "empty":
			d.Props[k] = ""
		case "typed":
			switch {
			case gotemplateIsURLKey(k):
				d.Props[k] = htmltemplate.URL("javascript:trusted('" + k + "')")
			case i%5 == 0:
				d.Props[k] = i*7 + 1
			case i%5 == 1:
				d.Props[k] = sp(k + " <ptr>")
			case i%5 == 2:
				d.Props[k] = (*string)(nil)
			case i%5 == 3:
				d.Props[k] = i%2 == 0
			default:
				d.Props[k] = htmltemplate.HTML("<i>" + k + "</i> &amp; <b>x</b>")
			}
		}
	}
	for _, k := range htmls {
		switch variant {
		case "escape":
			d.HTML[k] = htmltemplate.HTML("<strong>" + k + "</strong> &amp; <a href=\"/x?a=1&b=2\">link</a>")
		case "javascript":
			d.HTML[k] = htmltemplate.HTML("<script>alert('" + k + "')</script>")
		case "empty":
			d.HTML[k] = ""
		case "typed":
			d.HTML[k] = htmltemplate.HTML("<em>" + k + "</em>")
		}
	}
	text := func(k string) string {
		switch variant {
		case "escape":
			return k + ` <i>&</i> "q" 'a' é`
		case "javascript":
			return "javascript:" + k + "()"
		case "typed":
			return k + " typed"
		}
		return ""
	}
	url := func(k string) string {
		switch variant {
		case "escape":
			return "https://ex.com/" + k + "?a=b c&d=<e>"
		case "javascript":
			return "javascript:alert('" + k + "')"
		case "typed":
			return "mailto:" + k + "@ex.com"
		}
		return ""
	}
	if variant != "empty" {
		attachment := &email.EmailMessageAttachment{
			MessageAttachment: model.MessageAttachment{
				Fallback:   text("Fallback"),
				Color:      map[string]string{"escape": "#ff0000", "javascript": "expression(alert(1))", "typed": "red; background: url(x)"}[variant],
				AuthorName: text("AuthorName"),
				AuthorLink: url("AuthorLink"),
				AuthorIcon: url("AuthorIcon"),
				Title:      text("Title"),
				TitleLink:  url("TitleLink"),
				ImageURL:   url("ImageURL"),
				ThumbURL:   url("ThumbURL"),
				Footer:     text("Footer"),
				FooterIcon: url("FooterIcon"),
			},
			Pretext: htmltemplate.HTML("<p>" + text("Pretext") + "</p>"),
			Text:    htmltemplate.HTML("<p>" + text("Text") + "</p>"),
			FieldRows: []email.FieldRow{
				{Cells: []*model.MessageAttachmentField{{Title: text("Cell1"), Value: text("Value1")}}},
				{Cells: []*model.MessageAttachmentField{{Title: text("Cell2"), Value: 42}, {Title: text("Cell3"), Value: nil}}},
			},
		}
		d.Props["Posts"] = []postData{
			{
				SenderName:               text("SenderName"),
				ChannelName:              text("ChannelName"),
				Message:                  htmltemplate.HTML("<p>" + text("Message") + "</p>"),
				MessageURL:               url("MessageURL"),
				SenderPhoto:              url("SenderPhoto"),
				PostPhoto:                url("PostPhoto"),
				Time:                     text("Time"),
				ShowChannelIcon:          true,
				OtherChannelMembersCount: 3,
				MessageAttachments:       []*email.EmailMessageAttachment{attachment},
			},
			{
				SenderName:  text("SenderName2"),
				Message:     htmltemplate.HTML(text("Message2")),
				MessageURL:  "",
				SenderPhoto: url("SenderPhoto2"),
			},
		}
		d.Props["Browsers"] = []webBrowser{
			{LogoSrc: url("LogoSrc"), Title: text("BrowserTitle"), SupportedVersionString: text("Version"), Src: url("Src"), GetLatestString: text("GetLatest")},
			{LogoSrc: url("LogoSrc2"), Title: text("BrowserTitle2")},
		}
		d.Props["App"] = webMattermostApp{LogoSrc: url("AppLogo"), Title: text("AppTitle"), SupportedVersionString: text("AppVersion"), Label: text("AppLabel"), Link: url("AppLink"), InstallGuide: text("InstallGuide"), InstallGuideLink: url("InstallGuideLink")}
		d.Props["SystemBrowser"] = webSystemBrowser{LogoSrc: url("SysLogo"), Title: text("SysTitle"), SupportedVersionString: text("SysVersion"), LabelOpen: text("LabelOpen"), LinkOpen: url("LinkOpen"), LinkMakeDefault: url("LinkMakeDefault"), OrString: text("Or"), MakeDefaultString: text("MakeDefault")}
		d.Props["BulletListItems"] = []string{text("Bullet1"), text("Bullet2")}
	} else {
		d.Props["Posts"] = []postData{}
		d.Props["Browsers"] = []webBrowser{}
		d.Props["App"] = webMattermostApp{}
		d.Props["SystemBrowser"] = nil
		d.Props["BulletListItems"] = []string(nil)
	}
	return d
}

func gotemplateMattermostCorpus() (map[string]any, error) {
	files, err := filepath.Glob(filepath.Join(gotemplateTemplatesDir, "*.html"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	propSet, htmlSet := map[string]bool{}, map[string]bool{}
	var fileRecords []any
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return nil, err
		}
		fileRecords = append(fileRecords, map[string]any{"name": filepath.Base(f), "len": len(b)})
		for _, m := range gotemplatePropRe.FindAllStringSubmatch(string(b), -1) {
			propSet[m[1]] = true
		}
		for _, m := range gotemplateHTMLRe.FindAllStringSubmatch(string(b), -1) {
			htmlSet[m[1]] = true
		}
	}
	// Structured props are set explicitly.
	for _, k := range []string{"Posts", "Browsers", "App", "SystemBrowser", "BulletListItems"} {
		delete(propSet, k)
	}
	props := gtSortedKeys(propSet)
	htmls := gtSortedKeys(htmlSet)

	probe, err := templates.New(gotemplateTemplatesDir)
	if err != nil {
		return nil, err
	}
	_ = probe
	// The template names come from a parse of the same files through html/template itself.
	set, err := htmltemplate.ParseGlob(filepath.Join(gotemplateTemplatesDir, "*.html"))
	if err != nil {
		return nil, err
	}
	var names []string
	for _, t := range set.Templates() {
		names = append(names, t.Name())
	}
	sort.Strings(names)

	var variants []any
	for _, variant := range []string{"escape", "javascript", "empty", "typed", "missing"} {
		container, err := templates.New(gotemplateTemplatesDir)
		if err != nil {
			return nil, err
		}
		data := gotemplateMattermostData(variant, props, htmls)
		var runs []any
		for _, name := range names {
			out, err := container.RenderToString(name, data)
			runs = append(runs, map[string]any{"name": name, "out": out, "err": gtErrString(err)})
		}
		variants = append(variants, map[string]any{
			"variant": variant,
			"data":    gotemplateEncodeAny(data),
			"runs":    runs,
		})
	}
	return map[string]any{
		"files":    fileRecords,
		"names":    names,
		"variants": variants,
	}, nil
}

func gtSortedKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

