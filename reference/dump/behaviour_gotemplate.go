// gtCase is one template set: its sources parsed in order (the first becomes the set's root, the
// rest `New(name).Parse`), then each name in Exec executed in order against Data.
type gtCase struct {
	Name    string
	Sources [][2]string
	Exec    []string
	Data    any
	Option  string
}

func gtOne(name, src string, data any) gtCase {
	return gtCase{Name: name, Sources: [][2]string{{"t", src}}, Exec: []string{"t"}, Data: data}
}

