func writeGotemplateUnicodeTables(rustDir string) error {
	var b strings.Builder
	header := []string{
		"//! @generated by `reference/dump/behaviour_gotemplate.go` from Go's `unicode` package.",
		"//! DO NOT EDIT — re-run `cd reference/dump && go run . -only gotemplate` instead.",
		"//!",
		"//! `unicode.IsPrint` (read by `strconv.Quote`, `%q` and text/template's `JSEscape`) and",
		"//! `unicode.IsLetter` / `unicode.IsDigit` (the template lexer's `isAlphaNumeric`), as range",
		"//! tables. Unicode version: the **Go toolchain's**, not the Rust toolchain's.",
		"//!",
		"//! Sorted and non-overlapping, so a binary search applies.",
		"",
	}
	b.WriteString(strings.Join(header, "\n"))
	emitRanges(&b, "IS_PRINT_RANGES", "unicode.IsPrint", scanRuneRanges(unicode.IsPrint))
	emitRanges(&b, "IS_LETTER_RANGES", "unicode.IsLetter", scanRuneRanges(unicode.IsLetter))
	emitRanges(&b, "IS_DIGIT_RANGES", "unicode.IsDigit", scanRuneRanges(unicode.IsDigit))
	path := filepath.Join(rustDir, "unicode_tables.rs")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s\n", path)
	return nil
}

// writeGotemplateEntityTable emits crates/gotemplate/src/html/entity_table.rs: every named
// character reference `html.UnescapeString` knows (Go keeps the map unexported, so the names are
// read from the toolchain's own html/entity.go and each one's expansion is taken from
// UnescapeString itself, never from the source text). html/template decodes attribute values
// with it before running its context transitions.
func writeGotemplateEntityTable(rustDir string) error {
	src, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "src", "html", "entity.go"))
	if err != nil {
		return err
	}
	re := regexp.MustCompile(`(?m)^\s*"([A-Za-z0-9]+;?)":`)
	names := map[string]bool{}
	for _, m := range re.FindAllStringSubmatch(string(src), -1) {
		names[m[1]] = true
	}
	var sorted []string
	for n := range names {
		sorted = append(sorted, n)
	}
	sort.Strings(sorted)
	var b strings.Builder
	b.WriteString("//! @generated by `reference/dump/behaviour_gotemplate.go` from Go's `html` package.\n")
	b.WriteString("//! DO NOT EDIT — re-run `cd reference/dump && go run . -only gotemplate` instead.\n")
	b.WriteString("//!\n")
	b.WriteString("//! Every named character reference `html.UnescapeString` decodes, with its expansion as\n")
	b.WriteString("//! `html.UnescapeString(\"&\" + name)` returns it. Sorted by name for a binary search.\n\n")
	fmt.Fprintf(&b, "/// The %d entity names (with their `;` where the name has one) and expansions.\n", len(sorted))
	b.WriteString("#[rustfmt::skip]\npub(crate) static ENTITIES: &[(&str, &str)] = &[\n")
	for _, n := range sorted {
		probe := "&" + n
		if !strings.HasSuffix(n, ";") {
			// A name without its semicolon only decodes where no longer name matches; probe it
			// followed by a character that cannot extend a name.
			probe += " "
		}
		out := html.UnescapeString(probe)
		out = strings.TrimSuffix(out, " ")
		if out == strings.TrimSuffix(probe, " ") {
			return fmt.Errorf("entity %q did not decode", n)
		}
		fmt.Fprintf(&b, "    (%s, %s),\n", rustStringLiteral(n), rustStringLiteral(out))
	}
	b.WriteString("];\n")
	path := filepath.Join(rustDir, "html", "entity_table.rs")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s (%d entities)\n", path, len(sorted))
	return nil
}

// rustStringLiteral quotes s as a Rust string literal, escaping everything outside printable
// ASCII so the generated file is plain ASCII.
func rustStringLiteral(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		default:
			fmt.Fprintf(&b, "\\u{%x}", r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// gotemplateEncode turns a Go value into the type-tagged graph the Rust test decodes into a
// `gotemplate::Value`. Structs are flattened to the fields `FieldByName` can reach (promoted
// fields of embedded structs included, shadowed ones excluded), which is what a template sees.
func gotemplateEncode(v reflect.Value) any {
	if !v.IsValid() {
		return map[string]any{"t": "nil"}
	}
	switch v.Kind() {
	case reflect.Interface:
		if v.IsNil() {
			return map[string]any{"t": "nil"}
		}
		return gotemplateEncode(v.Elem())
	case reflect.Pointer:
		if v.IsNil() {
			return map[string]any{"t": "ptr", "v": nil, "type": v.Type().String()}
		}
		return map[string]any{"t": "ptr", "v": gotemplateEncode(v.Elem())}
	case reflect.Bool:
		return map[string]any{"t": "bool", "v": v.Bool()}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return map[string]any{"t": "int", "v": v.Int()}
	case reflect.Float32, reflect.Float64:
		return map[string]any{"t": "float", "v": strconv.FormatFloat(v.Float(), 'g', -1, 64)}
	case reflect.String:
		tag := "string"
		switch v.Type() {
		case reflect.TypeOf(htmltemplate.HTML("")):
			tag = "html"
		case reflect.TypeOf(htmltemplate.URL("")):
			tag = "url"
		case reflect.TypeOf(htmltemplate.CSS("")):
			tag = "css"
		case reflect.TypeOf(htmltemplate.JS("")):
			tag = "js"
		case reflect.TypeOf(htmltemplate.JSStr("")):
			tag = "jsstr"
		case reflect.TypeOf(htmltemplate.HTMLAttr("")):
			tag = "htmlattr"
		case reflect.TypeOf(htmltemplate.Srcset("")):
			tag = "srcset"
		}
		return map[string]any{"t": tag, "v": v.String()}
	case reflect.Slice, reflect.Array:
		items := make([]any, 0, v.Len())
		for i := 0; i < v.Len(); i++ {
			items = append(items, gotemplateEncode(v.Index(i)))
		}
		return map[string]any{"t": "list", "v": items}
	case reflect.Map:
		m := map[string]any{}
		iter := v.MapRange()
		for iter.Next() {
			m[iter.Key().String()] = gotemplateEncode(iter.Value())
		}
		return map[string]any{"t": "map", "v": m}
	case reflect.Struct:
		t := v.Type()
		fields := []any{}
		for _, f := range reflect.VisibleFields(t) {
			if !f.IsExported() {
				continue
			}
			sf, ok := t.FieldByName(f.Name)
			if !ok || !slices.Equal(sf.Index, f.Index) {
				continue
			}
			fields = append(fields, []any{f.Name, gotemplateEncode(v.FieldByIndex(f.Index))})
		}
		return map[string]any{"t": "struct", "name": t.String(), "v": fields}
	}
	panic(fmt.Sprintf("gotemplateEncode: unsupported kind %s", v.Kind()))
}

func gotemplateEncodeAny(x any) any {
	return gotemplateEncode(reflect.ValueOf(x))
}

func gtErrString(err error) any {
	if err == nil {
		return nil
	}
	return err.Error()
}

