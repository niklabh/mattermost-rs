func gtRun(c gtCase, html bool) map[string]any {
	rec := map[string]any{"name": c.Name, "sources": c.Sources, "exec": c.Exec, "data": gotemplateEncodeAny(c.Data), "option": c.Option}
	var runs []any
	if html {
		var root *htmltemplate.Template
		for _, s := range c.Sources {
			var t *htmltemplate.Template
			if root == nil {
				root = htmltemplate.New(s[0])
				if c.Option != "" {
					root.Option(c.Option)
				}
				t = root
			} else {
				t = root.New(s[0])
			}
			if _, err := t.Parse(s[1]); err != nil {
				rec["parse_err"] = err.Error()
				return rec
			}
		}
		for _, name := range c.Exec {
			var buf bytes.Buffer
			err := root.ExecuteTemplate(&buf, name, c.Data)
			runs = append(runs, map[string]any{"name": name, "out": buf.String(), "err": gtErrString(err)})
		}
	} else {
		var root *texttemplate.Template
		for _, s := range c.Sources {
			var t *texttemplate.Template
			if root == nil {
				root = texttemplate.New(s[0])
				if c.Option != "" {
					root.Option(c.Option)
				}
				t = root
			} else {
				t = root.New(s[0])
			}
			if _, err := t.Parse(s[1]); err != nil {
				rec["parse_err"] = err.Error()
				return rec
			}
		}
		for _, name := range c.Exec {
			var buf bytes.Buffer
			err := root.ExecuteTemplate(&buf, name, c.Data)
			runs = append(runs, map[string]any{"name": name, "out": buf.String(), "err": gtErrString(err)})
		}
	}
	rec["runs"] = runs
	return rec
}

func writeGotemplateBehaviourFixture(outDir, rustDir string) error {
	if err := writeGotemplateUnicodeTables(rustDir); err != nil {
		return err
	}
	if err := writeGotemplateEntityTable(rustDir); err != nil {
		return err
	}
	mm, err := gotemplateMattermostCorpus()
	if err != nil {
		return fmt.Errorf("mattermost corpus: %w", err)
	}
	var htmlCases, textCases []any
	for _, c := range gtHTMLCorpus() {
		htmlCases = append(htmlCases, gtRun(c, true))
	}
	for _, c := range gtTextCorpus() {
		textCases = append(textCases, gtRun(c, false))
	}
	// The same text corpus through html/template: the two differ on missing keys, nil pointers and
	// every escaper, which is the point of recording both.
	var textAsHTML []any
	for _, c := range gtTextCorpus() {
		textAsHTML = append(textAsHTML, gtRun(c, true))
	}
	out := map[string]any{
		"mattermost":   mm,
		"html":         htmlCases,
		"text":         textCases,
		"text_as_html": textAsHTML,
	}
	blob, err := json.MarshalIndent(out, "", " ")
	if err != nil {
		return err
	}
	path := filepath.Join(outDir, "behaviour_gotemplate.json")
	if err := os.WriteFile(path, append(blob, '\n'), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s (%d html, %d text cases)\n", path, len(htmlCases), len(textCases))
	return nil
}
