// Behavioural oracle for **Go's `text/template` and `html/template`**, which `crates/gotemplate`
// ports byte for byte. Written to fixtures/behaviour_gotemplate.json; `-only gotemplate` runs it
// alone. It also writes crates/gotemplate/src/unicode_tables.rs, the `unicode.IsPrint`,
// `IsLetter` and `IsDigit` tables the lexer, `strconv.Quote` and `JSEscape` read.
//
// Three corpora:
//
//   - `mattermost`: every template name Mattermost's real `templates.New(dir)` (a `ParseGlob` of
//     `server/templates/*.html`) defines, executed through `Container.RenderToString` with a fully
//     populated `templates.Data` in five variants chosen to exercise escaping (markup and quotes,
//     `javascript:` URLs, spaces and `%` in URLs, non-ASCII, trusted `template.HTML` and
//     `template.URL`, empty strings for every `{{if}}`, a nil Props map). Each variant runs every
//     name in sorted order on ONE container, as a long-lived server does — html/template escapes
//     lazily and remembers what it derived, so order is part of what is recorded.
//   - `html`: a targeted escaper corpus — each case is a template set, the names executed in
//     order, and the data; it records every output or error.
//   - `text`: the same shape through `text/template`, including parse errors.
//
// Data crosses to Rust as a type-tagged JSON graph built by reflection from the very Go value the
// template executed against (see gotemplateEncode), so the Rust test rebuilds an identical
// `Value` rather than a hand-written approximation.
//
// Determinism: fixed corpora, no clock, no randomness, no map iteration in the output path.

